package account

import "testing"

func TestSettlementCalendar(t *testing.T) {
	for _, tc := range []struct{ trade, want string }{
		{"2026-01-05", "2026-01-06"}, {"2026-01-09", "2026-01-12"},
		{"2026-01-16", "2026-01-20"}, {"2026-02-13", "2026-02-17"},
		{"2026-04-02", "2026-04-06"}, {"2026-05-22", "2026-05-26"},
		{"2026-06-18", "2026-06-22"}, {"2026-07-02", "2026-07-06"},
		{"2026-09-04", "2026-09-08"}, {"2026-10-09", "2026-10-13"},
		{"2026-11-10", "2026-11-12"}, {"2026-11-25", "2026-11-27"},
		{"2026-12-24", "2026-12-28"}, {"2026-12-31", "2027-01-04"},
		{"2021-06-17", "2021-06-18"}, {"2022-06-17", "2022-06-21"},
		{"2021-12-30", "2021-12-31"}, {"2023-11-09", "2023-11-10"},
		{"2018-12-04", "2018-12-06"}, {"2025-01-08", "2025-01-10"},
	} {
		t.Run(tc.trade, func(t *testing.T) {
			if got := SettlementDate(date(tc.trade)); got.Format("2006-01-02") != tc.want {
				t.Fatal(got, tc.want)
			}
		})
	}
}
